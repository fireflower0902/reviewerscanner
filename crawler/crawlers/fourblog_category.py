# 제공내역에서만 쓰는 약한 음식 신호 (점수 0.5)
_WEAK_FOOD = ["식사권", "자유이용권", "매장 제공", "매장제공", "미션", "주문", "2인", "음료"]


def _normalize(text: str) -> str:
    text = (text or "").lower()
    for pat, rep in _NORMALIZE:
        text = re.sub(pat, rep, text)
    return text


def _score(text: str, weight: float, scores: Dict[str, float]) -> None:
    for cat, words in _KEYWORDS.items():
        hits = sum(1 for w in words if w in text)
        if hits:
            scores[cat] = scores.get(cat, 0.0) + weight * min(hits, 3)   # 한 부분에서 최대 3개까지만 반영


def classify(title: str, hashtags: str, benefit: str) -> str:
    """제목/해시태그/제공내역 → 표준 카테고리(14종 중 하나)"""
    t = _normalize(re.sub(r"^\s*\[.*?\]\s*", "", title or ""))   # 앞의 [지역] 표기는 제외
    k = _normalize(hashtags)
    b = _normalize((benefit or "")[:120])

    scores: Dict[str, float] = {}
    _score(t, W_TITLE, scores)
    _score(k, W_TAGS, scores)
    _score(b, W_BENEFIT, scores)

    # 신호가 거의 없으면 제공내역의 약한 음식 신호 확인 (포블로그 방문형의 다수가 식당)
    if not scores or max(scores.values()) < 1.0:
        weak = sum(0.5 for w in _WEAK_FOOD if w in b)
        if weak >= 0.5:
            scores["음식점"] = scores.get("음식점", 0.0) + weak

    if not scores:
        return "기타"
    # 동점이면 특정 업종(뷰티·숙박 등)을 음식점보다 우선 (사전 순서)
    order = list(_KEYWORDS.keys())
    return max(scores.items(), key=lambda kv: (kv[1], -order.index(kv[0])))[0]
